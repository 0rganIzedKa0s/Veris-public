#!/usr/bin/env bash
# Build the always-on copy of the demo: the same page, no server behind it.
#
# The live demo is served BY the Orin over a Tailscale funnel, so when the board
# is unplugged the URL is not "degraded", it is gone — the in-page offline
# banner never even gets a chance to render. This build is what stays up: the
# sample images, their recorded runs, and the walkthrough, with everything that
# needs the hub switched off at the source.
#
# Usage: bash ops/build_static_demo.sh [output-dir]      (default: ./site)
set -euo pipefail

SRC="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${1:-$SRC/site}"
case "$OUT" in /*) ;; *) OUT="$(pwd)/$OUT";; esac   # see make_public_repo.sh
LIVE_URL="${LIVE_URL:-https://veris-orin.tail68ae71.ts.net/}"

rm -rf "$OUT"
mkdir -p "$OUT/samples"
cp "$SRC/demo/static/samples/"*.jpg "$SRC/demo/static/samples/recorded.json" "$OUT/samples/"
cp "$SRC/demo/static/samples/CREDITS.md" "$OUT/samples/"

# One source of truth for the page: inject the static flag and rewrite the
# absolute /static/samples/ paths (the live hub mounts them there; here they sit
# beside index.html). Anything else that differs is branched on VERIS_STATIC
# inside the page itself, so the two copies cannot drift apart.
python3 - "$SRC/demo/static/index.html" "$OUT/index.html" "$LIVE_URL" <<'PY'
import sys, pathlib
src, dst, live = sys.argv[1], sys.argv[2], sys.argv[3]
html = pathlib.Path(src).read_text()
flag = ('<script>window.VERIS_STATIC = true; '
        f'window.VERIS_LIVE_URL = {live!r};</script>\n<script>')
assert html.count("\n<script>\n") == 1, "expected exactly one page script block"
html = html.replace("\n<script>\n", "\n" + flag + "\n", 1)
html = html.replace('"/static/samples/', '"samples/')
html = html.replace("`/static/samples/", "`samples/")
assert "/static/samples/" not in html, "an absolute sample path survived"
assert "VERIS_STATIC = true" in html
pathlib.Path(dst).write_text(html)
PY

# GitHub Pages runs files through Jekyll by default, which silently drops paths
# it considers special. Nothing here needs it.
touch "$OUT/.nojekyll"

cat > "$OUT/README.md" <<MD
# Veris — recorded demo

Generated by \`ops/build_static_demo.sh\`; do not edit by hand.

A static copy of the Veris demo webapp that needs no server: the four sample
images, real runs recorded from the Jetson Orin Nano, and the walkthrough. It
exists so the demo still works when the board is powered down, since the live
demo is served by the board itself.

Live demo (when the board is on): $LIVE_URL
Sample image credits: \`samples/CREDITS.md\`
MD

echo "Built $OUT"
du -sh "$OUT"
